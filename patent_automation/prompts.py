    @classmethod
    def get_prompt(cls, prompt_name: str) -> str:
        """프롬프트 이름으로 프롬프트 텍스트 반환"""
        return getattr(cls, prompt_name, "")

    @classmethod
    def get_category_prompts(cls, category: str) -> dict:
        """카테고리별 프롬프트 목록 반환"""
        if category in cls.CATEGORIES:
            cat_info = cls.CATEGORIES[category]
            return {
                "name": cat_info["name"],
                "description": cat_info["description"],
                "prompts": {name: cls.get_prompt(name) for name in cat_info["prompts"]}
            }
        return {}

    @classmethod
    def get_all_categories(cls) -> dict:
        """모든 카테고리 정보 반환"""
        return cls.CATEGORIES

    @classmethod
    def build_combined_prompt(cls, prompt_names: list, custom_context: str = "") -> str:
        """여러 프롬프트를 조합하여 하나의 프롬프트 생성"""
        combined = []

        if custom_context:
            combined.append(f"[컨텍스트]\n{custom_context}\n")

        for name in prompt_names:
            prompt = cls.get_prompt(name)
            if prompt:
                combined.append(prompt)

        # 토큰 관리 프롬프트 자동 추가
        combined.append(cls.TOKEN_MANAGEMENT)

        return "\n\n".join(combined)
